# -*- coding: utf-8 -*-
"""Merge src/constants into compile/module_constants.py."""
from __future__ import annotations

from pathlib import Path
from typing import List

from constants_merge import find_duplicate_names_across_files, ordered_constant_py_files
from verify_slot_allocations import run_slot_allocation_verification

ROOT = Path(__file__).resolve().parents[1]
COMPILE_DIR = ROOT / "compile"
OUT_MAIN = COMPILE_DIR / "module_constants.py"
OUT_GENERATED = COMPILE_DIR / "module_constants.generated.py"


def build(*, verify_slots: bool = True) -> None:
    if verify_slots:
        result = run_slot_allocation_verification()
        counts = result["counts"]
        print(
            f"[build_constants] Slot verification: warning={counts.get('warning', 0)} "
            f"error={counts.get('error', 0)} info={counts.get('info', 0)} "
            f"({result['report_path']})"
        )
        if counts.get("error", 0):
            raise SystemExit(1)

    files = ordered_constant_py_files()
    if not files:
        raise SystemExit("[build_constants] No constants modules found under src/constants")

    dups = find_duplicate_names_across_files(files)
    if dups:
        for name, a, b in dups:
            print(f"[build_constants] ERROR: duplicate constant name:\n  {name}\n  {a}\n  {b}")
        raise SystemExit(1)

    banner = [
        "# -*- coding: cp1252 -*-",
        "# AUTO-GENERATED by build/build_constants.py - do not edit this file.",
        "# Edit constants under src/constants/.",
        "",
    ]
    parts: List[str] = ["\n".join(banner)]
    for fp in files:
        parts.append(f"# --- {fp.name} ---")
        parts.append(fp.read_text(encoding="utf-8", errors="replace").rstrip())
        parts.append("")

    merged = "\n".join(parts).rstrip() + "\n"
    OUT_MAIN.write_text(merged, encoding="cp1252", errors="replace")
    OUT_GENERATED.write_text(merged, encoding="cp1252", errors="replace")
    print(f"[build_constants] Wrote {OUT_MAIN}")
    print(f"[build_constants] Mirrored -> {OUT_GENERATED}")


if __name__ == "__main__":
    build()
