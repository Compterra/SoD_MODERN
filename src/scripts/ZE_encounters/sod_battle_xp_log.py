SCRIPTS = [
("sod_battle_xp_log_start",
 [
   (troop_get_xp, "$g_sod_battle_xp_start", "trp_player"),
   (store_character_level, "$g_sod_battle_level_start", "trp_player"),
   (assign, "$g_sod_battle_xp_gain", 0),
   (assign, "$g_sod_battle_level_gain", 0),
   (assign, "$g_sod_battle_xp_messages_suppressed", 1),
   (set_show_messages, 0),
 ]),

("sod_battle_xp_log_finish",
 [
   (try_begin),
     (eq, "$g_sod_battle_xp_messages_suppressed", 1),
     (troop_get_xp, ":xp_now", "trp_player"),
     (store_sub, "$g_sod_battle_xp_gain", ":xp_now", "$g_sod_battle_xp_start"),
     (val_max, "$g_sod_battle_xp_gain", 0),
     (store_character_level, ":level_now", "trp_player"),
     (store_sub, "$g_sod_battle_level_gain", ":level_now", "$g_sod_battle_level_start"),
     (val_max, "$g_sod_battle_level_gain", 0),
     (set_show_messages, 1),
     (try_begin),
       (gt, "$g_sod_battle_xp_gain", 0),
       (assign, reg1, "$g_sod_battle_xp_gain"),
       (try_begin),
         (gt, "$g_sod_battle_level_gain", 0),
         (assign, reg2, ":level_now"),
         (display_message, "@You earned {reg1} experience in the battle and advanced to level {reg2}.", 0x8fbc8f),
       (else_try),
         (display_message, "@You earned {reg1} experience in the battle.", 0x8fbc8f),
       (try_end),
     (else_try),
       (gt, "$g_sod_battle_level_gain", 0),
       (assign, reg2, ":level_now"),
       (display_message, "@You advanced to level {reg2}.", 0x8fbc8f),
     (try_end),
     (assign, "$g_sod_battle_xp_messages_suppressed", 0),
     (assign, "$g_sod_battle_xp_start", 0),
     (assign, "$g_sod_battle_level_start", 0),
     (assign, "$g_sod_battle_xp_gain", 0),
     (assign, "$g_sod_battle_level_gain", 0),
   (try_end),
 ]),
]
