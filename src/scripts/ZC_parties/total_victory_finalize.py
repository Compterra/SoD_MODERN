SCRIPTS = [
("total_victory_finalize",
    [
      (assign, reg0, 0),
      (try_begin),
        (le, "$g_ally_party", 0),
        (end_current_battle),
      (try_end),
      (call_script, "script_party_give_xp_and_gold", "p_encountered_party_backup"),
      (call_script, "script_sod_threat_board_note_party_defeated", "$g_enemy_party"),
      (try_begin),
        (eq, "$g_enemy_party", 0),
        (display_message, "str_error_string", red),
      (try_end),
      (call_script, "script_event_player_defeated_enemy_party", "$g_enemy_party"),
      (call_script, "script_clear_party_group", "$g_enemy_party"),
      (try_begin),
        (eq, "$g_next_menu", -1),

        (try_begin),
          (eq, "$g_sod_deactivate_forced_rest", 0),
          (call_script, "script_determine_and_start_forced_rest"),
        (else_try),
          (assign, "$g_is_in_forced_rest", -1),
          (assign, "$post_battle_forced_rest_time", 0),
          (assign, "$g_start_postbattle_forced_rest", -1),
        (try_end),

        (call_script, "script_post_battle_personality_clash_check"),

        (party_stack_get_troop_id, ":enemy_leader", "p_encountered_party_backup", 0),
        (try_begin),
          (is_between, ":enemy_leader", kingdom_heroes_begin, kingdom_heroes_end),
          (neg|is_between, "$g_encountered_party", centers_begin, centers_end),
          (store_troop_faction, ":enemy_leader_faction", ":enemy_leader"),

          (try_begin),
            (eq, "$g_ally_party", 0),
            (call_script, "script_add_log_entry", logent_lord_defeated_by_player, "trp_player", -1, ":enemy_leader", ":enemy_leader_faction"),
            (try_begin),
              (eq, "$cheat_mode", 1),
              (display_message, "@Victory comment. Player was alone", debug_color),
            (try_end),
          (else_try),
            (ge, "$g_strength_contribution_of_player", 40),
            (call_script, "script_add_log_entry", logent_lord_defeated_by_player, "trp_player", -1, ":enemy_leader", ":enemy_leader_faction"),
            (try_begin),
              (eq, "$cheat_mode", 1),
              (display_message, "@Ordinary victory comment. The player provided at least 40 percent forces.", debug_color),
            (try_end),
          (else_try),
            (gt, "$g_starting_strength_enemy_party", 1000),
            (call_script, "script_get_closest_center", "p_main_party"),
            (assign, ":battle_of_where", reg0),
            (call_script, "script_add_log_entry", logent_player_participated_in_major_battle, "trp_player", ":battle_of_where", -1, ":enemy_leader_faction"),
            (try_begin),
              (eq, "$cheat_mode", 1),
              (display_message, "@Player participation comment. The enemy had at least 1k starting strength.", debug_color),
            (try_end),
          (else_try),
            (eq, "$cheat_mode", 1),
            (display_message, "@No victory comment. The battle was small, and the player provided less than 40 percent of allied strength", debug_color),
          (try_end),
        (try_end),

        (val_add, "$g_total_victories", 1),
        (leave_encounter),
        (change_screen_return),
      (else_try),
        (assign, reg0, 1),
      (try_end),
  ]),
]
