SCRIPTS = [
("calculate_average_lord_army_strength",
  [  (assign, ":num_heroes", 0),
     (assign, ":total_force", 0),
    
    (try_for_range, ":kingdom_hero", kingdom_heroes_begin, kingdom_heroes_end),
    (neg|troop_slot_ge, ":kingdom_hero", slot_troop_prisoner_of_party, 0),
    (troop_slot_ge, ":kingdom_hero", slot_troop_leaded_party, 0),
	(troop_get_slot, ":party", ":kingdom_hero", slot_troop_leaded_party),
		(try_begin),
		(party_is_active, ":party"),
		(party_slot_ge, ":party", slot_party_cached_strength, 100),
		(val_add, ":num_heroes", 1),
		(party_get_slot, ":strength", ":party", slot_party_cached_strength),
		(val_add, ":total_force", ":strength"),
		(try_end),
   (try_end),
   (try_begin),
   (gt, ":num_heroes", 0),
   (store_div, "$g_average_lord_army_strength", ":total_force", ":num_heroes"),
   (else_try),
   (assign, "$g_average_lord_army_strength", 0),
   (try_end),
   (val_max, "$g_average_lord_army_strength", 1),
   (try_begin),
   (eq, "$g_sod_debug", 1),
   (assign, reg0, "$g_average_lord_army_strength"),
   (assign, reg1, ":num_heroes"),
   (display_log_message, "@Average strength {reg0} num heroes {reg1}", debug_color), # debug
   (try_end),
   ]),
]
