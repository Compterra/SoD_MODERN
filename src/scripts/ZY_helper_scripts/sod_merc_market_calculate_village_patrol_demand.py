# COST: O(patrols * villages) hourly snapshot plus O(faction villages) demand scoring.
SCRIPTS = [
("sod_merc_market_prepare_village_patrol_cache",
 [
   (store_current_hours, ":current_hour"),
   (assign, ":refresh_cache", 0),
   (try_begin),
     (neq, "$g_sod_merc_village_patrol_cache_initialized", 1),
     (assign, ":refresh_cache", 1),
   (else_try),
     (neq, "$g_sod_merc_village_patrol_cache_hour", ":current_hour"),
     (assign, ":refresh_cache", 1),
   (try_end),

   (try_begin),
     (eq, ":refresh_cache", 1),
     (assign, "$g_sod_merc_village_patrol_cache_initialized", 1),
     (assign, "$g_sod_merc_village_patrol_cache_hour", ":current_hour"),

     (try_for_range, ":village_no", villages_begin, villages_end),
       (party_slot_eq, ":village_no", slot_party_type, spt_village),
       (party_set_slot, ":village_no", slot_center_sod_merc_nearby_patrol_cache, 0),
     (try_end),

     # Coverage is independent of which kingdom asks for demand, so build it once.
     (try_for_parties, ":patrol_party"),
       (party_is_active, ":patrol_party"),
       (party_slot_eq, ":patrol_party", slot_party_type, spt_patrol),
       (party_slot_eq, ":patrol_party", slot_party_sod_support_type, sod_support_type_castle_patrol),
       (store_faction_of_party, ":patrol_faction", ":patrol_party"),
       (is_between, ":patrol_faction", native_kingdoms_begin, native_kingdoms_end),
       (faction_slot_eq, ":patrol_faction", slot_faction_state, sfs_active),
       (party_get_slot, ":patrol_status", ":patrol_party", slot_party_sod_patrol_status),
       (this_or_next|eq, ":patrol_status", sod_castle_patrol_status_forming),
       (this_or_next|eq, ":patrol_status", sod_castle_patrol_status_active),
       (eq, ":patrol_status", sod_castle_patrol_status_damaged),
       (try_for_range, ":village_no", villages_begin, villages_end),
         (party_slot_eq, ":village_no", slot_party_type, spt_village),
         (store_faction_of_party, ":village_faction", ":village_no"),
         (eq, ":village_faction", ":patrol_faction"),
         (neg|party_slot_eq, ":village_no", slot_village_state, svs_looted),
         (neg|party_slot_eq, ":village_no", slot_village_state, svs_deserted),
         (store_distance_to_party_from_party, ":patrol_distance", ":patrol_party", ":village_no"),
         (le, ":patrol_distance", 12),
         (party_get_slot, ":nearby_patrols", ":village_no", slot_center_sod_merc_nearby_patrol_cache),
         (val_add, ":nearby_patrols", 1),
         (party_set_slot, ":village_no", slot_center_sod_merc_nearby_patrol_cache, ":nearby_patrols"),
       (try_end),
     (try_end),
   (try_end),
 ]),

("sod_merc_market_calculate_village_patrol_demand",
 [
   (store_script_param_1, ":faction_no"),

   (assign, ":total_demand", 0),
   (assign, ":total_budget", 0),
   (assign, ":best_village", 0),
   (assign, ":best_score", 0),
   (assign, ":urgency", 0),

   (call_script, "script_sod_merc_market_prepare_village_patrol_cache"),

   (try_begin),
     (is_between, ":faction_no", native_kingdoms_begin, native_kingdoms_end),
     (faction_slot_eq, ":faction_no", slot_faction_state, sfs_active),

     (try_for_range, ":village_no", villages_begin, villages_end),
       (party_slot_eq, ":village_no", slot_party_type, spt_village),
       (store_faction_of_party, ":village_faction", ":village_no"),
       (eq, ":village_faction", ":faction_no"),
       (neg|party_slot_eq, ":village_no", slot_village_state, svs_looted),
       (neg|party_slot_eq, ":village_no", slot_village_state, svs_deserted),

       (party_get_slot, ":wealth", ":village_no", slot_town_wealth),
       (party_get_slot, ":prosperity", ":village_no", slot_town_prosperity),
       (party_get_slot, ":local_prosperity", ":village_no", slot_center_sod_local_prosperity),
       (party_get_slot, ":health", ":village_no", slot_center_sod_local_health),
       (party_get_slot, ":looter_pressure", ":village_no", slot_center_sod_looter_raid_pressure),
       (party_get_slot, ":garrison_losses", ":village_no", slot_center_sod_looter_garrison_losses_recent),
       (party_get_slot, ":militia_losses", ":village_no", slot_center_sod_looter_militia_losses_recent),
       (val_max, ":wealth", 0),
       (val_clamp, ":prosperity", 0, 101),
       (val_clamp, ":local_prosperity", 0, 101),
       (val_clamp, ":health", 0, 101),
       (val_max, ":looter_pressure", 0),
       (val_max, ":garrison_losses", 0),
       (val_max, ":militia_losses", 0),

       (call_script, "script_sod_get_center_population_capacity_profile", ":village_no"),
       (assign, ":capacity_pct", reg2),
       (call_script, "script_sod_get_center_food_profile", ":village_no"),
       (assign, ":food_security", reg4),
       (assign, ":food_pressure", reg6),
       (call_script, "script_sod_get_center_security_profile", ":village_no"),
       (assign, ":security", reg1),
       (assign, ":raid_resistance", reg3),
       (assign, ":patrol_response", reg7),
       (assign, ":vulnerability", reg10),
       (assign, ":contract_security", reg11),

       (party_get_slot, ":nearby_patrols", ":village_no", slot_center_sod_merc_nearby_patrol_cache),
       (val_max, ":nearby_patrols", 0),

       (assign, ":critical_resilience_need", 0),
       (try_begin),
         (this_or_next|lt, ":health", 35),
         (this_or_next|lt, ":capacity_pct", 50),
         (lt, ":food_security", 500),
         (assign, ":critical_resilience_need", 1),
       (try_end),

       (assign, ":score", 0),
       (try_begin),
         (ge, ":wealth", 2500),
         (store_sub, ":wealth_score", ":wealth", 2500),
         (val_div, ":wealth_score", 250),
         (val_clamp, ":wealth_score", 0, 26),
         (val_add, ":score", ":wealth_score"),
       (try_end),
       (try_begin),
         (ge, ":prosperity", 60),
         (store_sub, ":prosperity_score", ":prosperity", 55),
         (val_div, ":prosperity_score", 3),
         (val_add, ":score", ":prosperity_score"),
       (try_end),
       (store_div, ":local_prosperity_score", ":local_prosperity", 10),
       (val_add, ":score", ":local_prosperity_score"),
       (store_div, ":pressure_score", ":looter_pressure", 4),
       (val_add, ":score", ":pressure_score"),
       (store_add, ":loss_pressure", ":garrison_losses", ":militia_losses"),
       (val_div, ":loss_pressure", 2),
       (val_add, ":score", ":loss_pressure"),
       (store_div, ":vulnerability_score", ":vulnerability", 4),
       (val_add, ":score", ":vulnerability_score"),
       (try_begin),
         (lt, ":health", 55),
         (store_sub, ":health_pressure", 55, ":health"),
         (val_div, ":health_pressure", 4),
         (val_add, ":score", ":health_pressure"),
       (try_end),
       (try_begin),
         (lt, ":capacity_pct", 75),
         (store_sub, ":population_pressure", 75, ":capacity_pct"),
         (val_div, ":population_pressure", 6),
         (val_add, ":score", ":population_pressure"),
       (try_end),
       (try_begin),
         (lt, ":food_security", 700),
         (store_sub, ":food_security_pressure", 700, ":food_security"),
         (val_div, ":food_security_pressure", 50),
         (val_add, ":score", ":food_security_pressure"),
       (try_end),
       (try_begin),
         (gt, ":food_pressure", 0),
         (store_div, ":food_pressure_score", ":food_pressure", 3),
         (val_add, ":score", ":food_pressure_score"),
       (try_end),

       (store_div, ":security_relief", ":security", 12),
       (val_sub, ":score", ":security_relief"),
       (store_div, ":resistance_relief", ":raid_resistance", 10),
       (val_sub, ":score", ":resistance_relief"),
       (store_div, ":response_relief", ":patrol_response", 12),
       (val_sub, ":score", ":response_relief"),
       (store_div, ":contract_relief", ":contract_security", 5),
       (val_sub, ":score", ":contract_relief"),
       (store_mul, ":patrol_relief", ":nearby_patrols", 18),
       (val_sub, ":score", ":patrol_relief"),

       # Low-value villages still need protection when hunger or sickness risks collapse.
       (try_begin),
         (lt, ":wealth", 1800),
         (lt, ":looter_pressure", 20),
         (eq, ":critical_resilience_need", 0),
         (assign, ":score", 0),
       (try_end),
       (val_clamp, ":score", 0, 45),

       (try_begin),
         (gt, ":score", 0),
         (val_add, ":total_demand", ":score"),
         (store_div, ":village_budget", ":wealth", 20),
         (store_mul, ":prosperity_budget", ":prosperity", 3),
         (val_add, ":village_budget", ":prosperity_budget"),
         (try_begin),
           (eq, ":critical_resilience_need", 1),
           (val_add, ":village_budget", 150),
         (try_end),
         (try_begin),
           (ge, ":score", 25),
           (val_add, ":village_budget", 250),
         (try_end),
         (val_clamp, ":village_budget", 0, 900),
         (val_add, ":total_budget", ":village_budget"),
         (try_begin),
           (gt, ":score", ":best_score"),
           (assign, ":best_score", ":score"),
           (assign, ":best_village", ":village_no"),
         (try_end),
       (try_end),
     (try_end),

     (val_clamp, ":total_demand", 0, 40),
     (val_clamp, ":total_budget", 0, 1800),
     (try_begin),
       (ge, ":best_score", 30),
       (assign, ":urgency", 3),
     (else_try),
       (ge, ":best_score", 16),
       (assign, ":urgency", 2),
     (else_try),
       (gt, ":best_score", 0),
       (assign, ":urgency", 1),
     (try_end),

     (faction_set_slot, ":faction_no", slot_faction_sod_merc_village_patrol_demand, ":total_demand"),
     (faction_set_slot, ":faction_no", slot_faction_sod_merc_village_patrol_budget, ":total_budget"),
     (faction_set_slot, ":faction_no", slot_faction_sod_merc_village_patrol_target, ":best_village"),
     (faction_set_slot, ":faction_no", slot_faction_sod_merc_village_patrol_urgency, ":urgency"),
   (try_end),

   (assign, reg0, ":total_demand"),
   (assign, reg1, ":total_budget"),
   (assign, reg2, ":best_village"),
   (assign, reg3, ":urgency"),
 ]),
]
