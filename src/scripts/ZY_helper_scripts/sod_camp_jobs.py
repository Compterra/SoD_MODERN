("sod_camp_job_unlame_random_horse",
 [
   (assign, ":candidate_count", 0),
   (assign, ":selected_troop", -1),
   (assign, ":selected_slot", -1),

   (troop_get_inventory_slot, ":item_no", "trp_player", ek_horse),
   (try_begin),
     (ge, ":item_no", 0),
     (item_get_type, ":item_type", ":item_no"),
     (eq, ":item_type", itp_type_horse),
     (troop_get_inventory_slot_modifier, ":imod", "trp_player", ek_horse),
     (eq, ":imod", imod_lame),
     (val_add, ":candidate_count", 1),
     (assign, ":selected_troop", "trp_player"),
     (assign, ":selected_slot", ek_horse),
   (try_end),

   (try_for_range, ":troop_no", companions_begin, companions_end),
     (main_party_has_troop, ":troop_no"),
     (troop_get_inventory_slot, ":item_no", ":troop_no", ek_horse),
     (ge, ":item_no", 0),
     (item_get_type, ":item_type", ":item_no"),
     (eq, ":item_type", itp_type_horse),
     (troop_get_inventory_slot_modifier, ":imod", ":troop_no", ek_horse),
     (eq, ":imod", imod_lame),
     (val_add, ":candidate_count", 1),
     (store_random_in_range, ":roll", 0, ":candidate_count"),
     (eq, ":roll", 0),
     (assign, ":selected_troop", ":troop_no"),
     (assign, ":selected_slot", ek_horse),
   (try_end),

   (troop_get_inventory_capacity, ":capacity", "trp_player"),
   (try_for_range, ":slot_no", 0, ":capacity"),
     (troop_get_inventory_slot, ":item_no", "trp_player", ":slot_no"),
     (ge, ":item_no", 0),
     (item_get_type, ":item_type", ":item_no"),
     (eq, ":item_type", itp_type_horse),
     (troop_get_inventory_slot_modifier, ":imod", "trp_player", ":slot_no"),
     (eq, ":imod", imod_lame),
     (val_add, ":candidate_count", 1),
     (store_random_in_range, ":roll", 0, ":candidate_count"),
     (eq, ":roll", 0),
     (assign, ":selected_troop", "trp_player"),
     (assign, ":selected_slot", ":slot_no"),
   (try_end),

   (try_begin),
     (gt, ":candidate_count", 0),
     (ge, ":selected_troop", 0),
     (ge, ":selected_slot", 0),
     (troop_set_inventory_slot_modifier, ":selected_troop", ":selected_slot", imod_plain),
     (assign, reg0, 1),
   (else_try),
     (assign, reg0, 0),
   (try_end),
 ]),

