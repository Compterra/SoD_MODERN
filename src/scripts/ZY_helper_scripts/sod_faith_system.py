("sod_initialize_center_faith_support",
  [
    (store_script_param, ":center_no", 1),

    (try_begin),
      (gt, ":center_no", 0),
      (neg|party_slot_eq, ":center_no", slot_center_sod_faith_migrated, 1),
      (store_faction_of_party, ":center_faction", ":center_no"),
      (call_script, "script_sod_get_faction_faith_preference", ":center_faction"),
      (assign, ":owner_faith", reg0),

      (party_get_slot, ":legacy_faith", ":center_no", slot_center_sod_local_faith),
      (store_add, ":owner_support", ":legacy_faith", 50),
      (val_clamp, ":owner_support", 10, 86),
      (assign, ":minority_support", 12),
      (assign, ":secondary_support", 24),

      (try_for_range, ":faith_id", sod_faiths_begin, sod_faiths_end),
        (try_begin),
          (eq, ":faith_id", ":owner_faith"),
          (call_script, "script_sod_set_center_faith_support", ":center_no", ":faith_id", ":owner_support"),
        (else_try),
          (store_add, ":seed", ":center_no", ":faith_id"),
          (store_mod, ":seed_mod", ":seed", 5),
          (eq, ":seed_mod", 0),
          (call_script, "script_sod_set_center_faith_support", ":center_no", ":faith_id", ":secondary_support"),
        (else_try),
          (call_script, "script_sod_set_center_faith_support", ":center_no", ":faith_id", ":minority_support"),
        (try_end),
      (try_end),

      (party_set_slot, ":center_no", slot_center_sod_faith_migrated, 1),
      (call_script, "script_sod_recalculate_center_faith_profile", ":center_no"),
    (try_end),
  ]),

("sod_recalculate_center_faith_profile",
  [
    (store_script_param, ":center_no", 1),

    (assign, ":dominant_faith", cb_the_one),
    (assign, ":dominant_support", -1),
    (assign, ":second_support", 0),
    (try_for_range, ":faith_id", sod_faiths_begin, sod_faiths_end),
      (call_script, "script_sod_get_center_faith_support", ":center_no", ":faith_id"),
      (assign, ":support", reg0),
      (try_begin),
        (gt, ":support", ":dominant_support"),
        (assign, ":second_support", ":dominant_support"),
        (assign, ":dominant_support", ":support"),
        (assign, ":dominant_faith", ":faith_id"),
      (else_try),
        (gt, ":support", ":second_support"),
        (assign, ":second_support", ":support"),
      (try_end),
    (try_end),

    (store_sub, ":faith_tension", ":second_support", ":dominant_support"),
    (val_add, ":faith_tension", 50),
    (val_clamp, ":faith_tension", 0, 101),

    (assign, ":institution_strength", 0),
    (try_begin),
      (party_slot_eq, ":center_no", slot_center_has_temple, 1),
      (val_add, ":institution_strength", 35),
    (try_end),
    (try_begin),
      (party_slot_eq, ":center_no", slot_center_has_chapel, 1),
      (val_add, ":institution_strength", 25),
    (try_end),
    (try_begin),
      (party_slot_eq, ":center_no", slot_center_has_monastery, 1),
      (val_add, ":institution_strength", 30),
    (try_end),
    (try_begin),
      (party_slot_eq, ":center_no", slot_center_has_shrine, 1),
      (val_add, ":institution_strength", 15),
    (try_end),
    (call_script, "script_sod_get_center_modifier", ":center_no", sod_center_modifier_faith_stability_flat),
    (val_add, ":institution_strength", reg0),
    (val_clamp, ":institution_strength", 0, 101),

    (party_set_slot, ":center_no", slot_center_sod_dominant_faith, ":dominant_faith"),
    (party_set_slot, ":center_no", slot_center_sod_faith_tension, ":faith_tension"),
    (party_set_slot, ":center_no", slot_center_sod_faith_institution_strength, ":institution_strength"),

    (try_begin),
      (gt, "$g_sod_faith", 0),
      (call_script, "script_sod_get_center_faith_support", ":center_no", "$g_sod_faith"),
      (party_set_slot, ":center_no", slot_center_sod_local_faith, reg0),
    (try_end),

    (assign, reg0, ":dominant_faith"),
    (assign, reg1, ":dominant_support"),
    (assign, reg2, ":second_support"),
    (assign, reg3, ":faith_tension"),
    (assign, reg4, ":institution_strength"),
  ]),

