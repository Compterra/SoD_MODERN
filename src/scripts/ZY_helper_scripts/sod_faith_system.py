("sod_apply_weekly_population_faith_gain",
  [
    (assign, ":weighted_faith_population", 0),
    (assign, ":realm_population", 0),
    (assign, ":center_count", 0),
    (assign, ":faith_gain", 0),

    (try_begin),
      (is_between, "$g_sod_faith", sod_faiths_begin, sod_faiths_end),
      (try_for_range, ":center_no", centers_begin, centers_end),
        (store_faction_of_party, ":center_faction", ":center_no"),
        (this_or_next|eq, ":center_faction", "fac_player_supporters_faction"),
        (eq, ":center_faction", "fac_player_faction"),

        (party_get_slot, ":population", ":center_no", slot_center_sod_local_population),
        (try_begin),
          (le, ":population", 0),
          (call_script, "script_sod_normalize_center_population", ":center_no"),
          (party_get_slot, ":population", ":center_no", slot_center_sod_local_population),
        (try_end),
        (try_begin),
          (le, ":population", 0),
          (try_begin),
            (party_slot_eq, ":center_no", slot_party_type, spt_town),
            (assign, ":population", 1200),
          (else_try),
            (party_slot_eq, ":center_no", slot_party_type, spt_castle),
            (assign, ":population", 350),
          (else_try),
            (assign, ":population", 450),
          (try_end),
        (try_end),

        (call_script, "script_sod_get_center_faith_profile", ":center_no"),
        (assign, ":player_support", reg2),

        (assign, ":total_support", 0),
        (try_for_range, ":faith_id", sod_faiths_begin, sod_faiths_end),
          (call_script, "script_sod_get_center_faith_support", ":center_no", ":faith_id"),
          (val_add, ":total_support", reg0),
        (try_end),
        (val_max, ":total_support", 1),

        (store_mul, ":center_weighted_faith", ":population", ":player_support"),
        (val_div, ":center_weighted_faith", ":total_support"),
        (val_add, ":weighted_faith_population", ":center_weighted_faith"),
        (val_add, ":realm_population", ":population"),
        (val_add, ":center_count", 1),
      (try_end),

      (store_div, ":faith_gain", ":weighted_faith_population", 500),
      (try_begin),
        (ge, ":weighted_faith_population", 100),
        (val_max, ":faith_gain", 1),
      (try_end),
      (val_clamp, ":faith_gain", 0, 26),
      (try_begin),
        (gt, ":faith_gain", 0),
        (val_add, "$g_sod_global_faith", ":faith_gain"),
        (val_clamp, "$g_sod_global_faith", -2000, 2001),
      (try_end),
    (try_end),

    (assign, reg0, ":faith_gain"),
    (assign, reg1, ":weighted_faith_population"),
    (assign, reg2, ":realm_population"),
    (assign, reg3, ":center_count"),
  ]),

