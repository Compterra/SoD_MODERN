# COST: medium
SCRIPTS = [
("cf_sod_center_has_bank_service",
 [
   (store_script_param_1, ":center_no"),
   (is_between, ":center_no", towns_begin, towns_end),
   (this_or_next|party_slot_eq, ":center_no", slot_center_has_bank, 1),
   (party_slot_eq, ":center_no", slot_center_has_manufacture, 1),
 ]),

("sod_bank_ensure_valid_interest_rate",
 [
   (try_begin),
     (this_or_next|lt, "$g_sod_bank_interest_rate", 30),
     (gt, "$g_sod_bank_interest_rate", 150),
     (call_script, "script_sod_bank_set_interest_rate"),
   (try_end),
 ]),

("sod_bank_set_interest_rate",
 [
   (assign, ":prosperity_total", 0),
   (assign, ":town_count", 0),
   (try_for_range, ":town_no", towns_begin, towns_end),
     (party_get_slot, ":prosperity", ":town_no", slot_town_prosperity),
     (val_max, ":prosperity", 0),
     (val_add, ":prosperity_total", ":prosperity"),
     (val_add, ":town_count", 1),
   (try_end),

   (assign, ":average_prosperity", 50),
   (try_begin),
     (gt, ":town_count", 0),
     (store_div, ":average_prosperity", ":prosperity_total", ":town_count"),
   (try_end),

   (store_random_in_range, ":rate", 30, 61),
   (store_div, ":prosperity_bonus", ":average_prosperity", 2),
   (val_add, ":rate", ":prosperity_bonus"),
   (val_clamp, ":rate", 30, 151),
   (assign, "$g_sod_bank_interest_rate", ":rate"),
   (assign, reg0, ":rate"),
 ]),

("sod_bank_store_report_registers",
 [
   (call_script, "script_sod_bank_ensure_valid_interest_rate"),
   (store_troop_gold, reg1, "trp_player"),
   (store_troop_gold, reg2, "trp_sod_bankvault_possessions"),
   (assign, reg3, "$g_sod_bank_interest_rate"),
   (store_mul, reg4, reg2, reg3),
   (val_div, reg4, 10000),
   (store_add, reg9, reg2, reg4),
   (assign, reg5, "$g_player_debt_to_party_members"),
   (assign, reg6, "$g_player_party_morale_modifier_debt"),
   (assign, reg7, "$debt_to_merchants_guild"),
   (assign, reg8, 0),
   (str_store_string, s21, "@The bank's clerks keep a global account for your campaign."),
   (try_begin),
     (is_between, "$current_town", towns_begin, towns_end),
     (party_slot_eq, "$current_town", slot_center_has_manufacture, 1),
     (neg|party_slot_eq, "$current_town", slot_center_has_bank, 1),
     (str_store_string, s21, "@The manufacture's counting-house honors old bank ledgers for your campaign."),
   (try_end),
   (try_for_range, ":guild_faction", guilds_begin, guilds_end),
     (faction_get_slot, ":guild_debt", ":guild_faction", player_debt_to_faction),
     (val_max, ":guild_debt", 0),
     (val_add, reg8, ":guild_debt"),
   (try_end),

   (str_store_string, s20, "@No outstanding company or guild warnings."),
   (try_begin),
     (this_or_next|gt, reg5, 0),
     (this_or_next|gt, reg7, 0),
     (gt, reg8, 0),
     (str_store_string, s20, "@Ledger warnings:"),
     (try_begin),
       (gt, reg5, 0),
       (str_store_string, s20, "@{s20}^Company arrears: {reg5} denars. Morale debt pressure: {reg6}."),
     (try_end),
     (try_begin),
       (gt, reg7, 0),
       (str_store_string, s20, "@{s20}^Merchant guild debt: {reg7} denars."),
     (try_end),
     (try_begin),
       (gt, reg8, 0),
       (str_store_string, s20, "@{s20}^Mercenary pact debt: {reg8} denars."),
     (try_end),
     (str_store_string, s20, "@{s20}^Banked coin is protected in the ledger, but it will not automatically pay wages or guild debts."),
   (try_end),
 ]),

("sod_bank_deposit",
 [
   (store_script_param_1, ":requested_amount"),
   (assign, reg0, 0),
   (try_begin),
     (gt, ":requested_amount", 0),
     (store_troop_gold, ":player_gold", "trp_player"),
     (assign, ":deposit_amount", ":requested_amount"),
     (val_min, ":deposit_amount", ":player_gold"),
     (gt, ":deposit_amount", 0),
     (troop_remove_gold, "trp_player", ":deposit_amount"),
     (troop_add_gold, "trp_sod_bankvault_possessions", ":deposit_amount"),
     (assign, reg0, ":deposit_amount"),
     (assign, reg1, ":deposit_amount"),
     (display_message, "@You deposit {reg1} denars with the bank.", 0x99CCFF),
   (else_try),
     (display_message, "@You do not have enough denars to make that deposit.", 0xFFCC66),
   (try_end),
 ]),

("sod_bank_deposit_surplus",
 [
   (store_script_param_1, ":reserve_amount"),
   (assign, reg0, 0),
   (store_troop_gold, ":player_gold", "trp_player"),
   (store_sub, ":deposit_amount", ":player_gold", ":reserve_amount"),
   (try_begin),
     (gt, ":deposit_amount", 0),
     (troop_remove_gold, "trp_player", ":deposit_amount"),
     (troop_add_gold, "trp_sod_bankvault_possessions", ":deposit_amount"),
     (assign, reg0, ":deposit_amount"),
     (assign, reg1, ":deposit_amount"),
     (assign, reg2, ":reserve_amount"),
     (display_message, "@You deposit {reg1} denars and keep {reg2} denars for the road.", 0x99CCFF),
   (else_try),
     (assign, reg1, ":reserve_amount"),
     (display_message, "@You do not have more than {reg1} denars to spare.", 0xFFCC66),
   (try_end),
 ]),

("sod_bank_withdraw",
 [
   (store_script_param_1, ":requested_amount"),
   (assign, reg0, 0),
   (store_troop_gold, ":bank_balance", "trp_sod_bankvault_possessions"),
   (assign, ":withdraw_amount", ":requested_amount"),
   (try_begin),
     (le, ":withdraw_amount", 0),
     (assign, ":withdraw_amount", ":bank_balance"),
   (try_end),
   (val_min, ":withdraw_amount", ":bank_balance"),
   (try_begin),
     (gt, ":withdraw_amount", 0),
     (troop_remove_gold, "trp_sod_bankvault_possessions", ":withdraw_amount"),
     (call_script, "script_troop_add_gold", "trp_player", ":withdraw_amount"),
     (assign, reg0, ":withdraw_amount"),
     (assign, reg1, ":withdraw_amount"),
     (display_message, "@You withdraw {reg1} denars from the bank.", 0x99CCFF),
   (else_try),
     (display_message, "@There are no denars available in your bank account.", 0xFFCC66),
   (try_end),
 ]),

("sod_bank_apply_weekly_interest",
 [
   (call_script, "script_sod_bank_ensure_valid_interest_rate"),
   (assign, ":old_rate", "$g_sod_bank_interest_rate"),
   (call_script, "script_sod_bank_set_interest_rate"),
   (assign, ":new_rate", reg0),
   (store_troop_gold, ":bank_balance", "trp_sod_bankvault_possessions"),
   (try_begin),
     (gt, ":bank_balance", 0),
     (store_mul, ":interest", ":bank_balance", ":old_rate"),
     (val_div, ":interest", 10000),
     (try_begin),
       (gt, ":interest", 0),
       (troop_add_gold, "trp_sod_bankvault_possessions", ":interest"),
       (val_add, ":bank_balance", ":interest"),
     (try_end),
     (assign, reg1, ":interest"),
     (assign, reg2, ":bank_balance"),
     (assign, reg3, ":new_rate"),
     (display_message, "@Bank report: interest {reg1} denars. Balance {reg2} denars. New weekly rate {reg3}/10000.", 0x99CCFF),
   (try_end),
 ]),
]
