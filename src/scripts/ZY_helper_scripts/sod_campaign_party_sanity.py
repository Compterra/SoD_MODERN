# COST: O(num_active_parties), hourly. Lightweight sanity repair for campaign party faction/ignore state drift.
SCRIPTS = [
("sod_campaign_party_sanity",
 [
   (store_current_hours, ":cur_hours"),
   (assign, ":fixed_parties", 0),
   (try_for_parties, ":party_no"),
     (party_is_active, ":party_no"),
     (party_get_slot, ":party_type", ":party_no", slot_party_type),
     (assign, ":expected_faction", -1),
     (try_begin),
       (eq, ":party_type", spt_kingdom_hero_party),
       (party_stack_get_troop_id, ":leader_troop", ":party_no", 0),
       (is_between, ":leader_troop", kingdom_heroes_begin, kingdom_heroes_end),
       (store_troop_faction, ":leader_faction", ":leader_troop"),
       (is_between, ":leader_faction", kingdoms_begin, kingdoms_end),
       (assign, ":expected_faction", ":leader_faction"),
     (else_try),
       (this_or_next|eq, ":party_type", spt_ai_mercenaries),
       (eq, ":party_type", spt_mercenary_lord_party),
       (party_get_slot, ":boss_troop", ":party_no", slot_party_boss),
       (is_between, ":boss_troop", kingdom_heroes_begin, kingdom_heroes_end),
       (store_troop_faction, ":boss_faction", ":boss_troop"),
       (is_between, ":boss_faction", kingdoms_begin, kingdoms_end),
       (assign, ":expected_faction", ":boss_faction"),
     (else_try),
       (this_or_next|eq, ":party_type", spt_ai_mercenaries),
       (eq, ":party_type", spt_mercenary_lord_party),
       (party_get_slot, ":commander_party", ":party_no", slot_party_commander_party),
       (gt, ":commander_party", 0),
       (party_is_active, ":commander_party"),
       (store_faction_of_party, ":commander_faction", ":commander_party"),
       (is_between, ":commander_faction", kingdoms_begin, kingdoms_end),
       (assign, ":expected_faction", ":commander_faction"),
     (try_end),
     (try_begin),
       (gt, ":expected_faction", 0),
       (store_faction_of_party, ":cur_faction", ":party_no"),
       (neq, ":cur_faction", ":expected_faction"),
       (this_or_next|eq, ":cur_faction", "fac_neutral"),
       (this_or_next|eq, ":cur_faction", "fac_commoners"),
       (this_or_next|eq, ":cur_faction", "fac_player_faction"),
       (neg|is_between, ":cur_faction", kingdoms_begin, kingdoms_end),
       (party_set_faction, ":party_no", ":expected_faction"),
       (val_add, ":fixed_parties", 1),
     (try_end),
     (try_begin),
       (gt, ":expected_faction", 0),
       (store_relation, ":relation_to_player", ":expected_faction", "fac_player_supporters_faction"),
       (lt, ":relation_to_player", 0),
       (party_get_slot, ":ignore_until", ":party_no", slot_party_ignore_player_until),
       (this_or_next|le, ":ignore_until", 0),
       (le, ":ignore_until", ":cur_hours"),
       (party_set_slot, ":party_no", slot_party_ignore_player_until, 0),
       (party_ignore_player, ":party_no", 0),
     (try_end),
     (try_begin),
       (this_or_next|eq, ":party_type", spt_ai_mercenaries),
       (eq, ":party_type", spt_mercenary_lord_party),
       (party_get_attached_to, ":attached_to", ":party_no"),
       (gt, ":attached_to", 0),
       (party_is_active, ":attached_to"),
       (party_get_attached_to, ":attached_parent", ":attached_to"),
       (gt, ":attached_parent", 0),
       (try_begin),
         (is_between, ":attached_parent", centers_begin, centers_end),
         (party_is_active, ":attached_parent"),
         (party_attach_to_party, ":party_no", ":attached_parent"),
       (else_try),
         (party_detach, ":party_no"),
         (party_get_slot, ":commander_party", ":party_no", slot_party_commander_party),
         (try_begin),
           (gt, ":commander_party", 0),
           (party_is_active, ":commander_party"),
           (party_set_ai_object, ":party_no", ":commander_party"),
           (party_set_ai_behavior, ":party_no", ai_bhvr_escort_party),
         (else_try),
           (party_set_slot, ":party_no", slot_party_commander_party, -1),
           (party_set_ai_behavior, ":party_no", ai_bhvr_patrol_location),
         (try_end),
       (try_end),
       (val_add, ":fixed_parties", 1),
     (else_try),
       (this_or_next|eq, ":party_type", spt_ai_mercenaries),
       (eq, ":party_type", spt_mercenary_lord_party),
       (party_get_attached_to, ":attached_to", ":party_no"),
       (eq, ":attached_to", ":party_no"),
       (party_detach, ":party_no"),
       (val_add, ":fixed_parties", 1),
     (try_end),
   (try_end),
   (try_begin),
     (gt, ":fixed_parties", 0),
     (eq, "$g_sod_debug", 1),
     (assign, reg1, ":fixed_parties"),
     (display_message, "@Campaign party sanity restored {reg1} faction identity issue(s).", debug_color),
   (try_end),
 ]),
]
