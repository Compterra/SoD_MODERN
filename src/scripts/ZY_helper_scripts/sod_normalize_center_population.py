# COST: O(1)
SCRIPTS = [
("sod_normalize_center_population",
  [
    (store_script_param, ":center_no", 1),
    (assign, reg0, 0),
    (try_begin),
      (is_between, ":center_no", centers_begin, centers_end),
      (party_get_slot, ":population", ":center_no", slot_center_sod_local_population),
      (assign, ":recovery_floor", 0),
      (assign, ":population_cap", 0),
      (try_begin),
        (is_between, ":center_no", villages_begin, villages_end),
        (assign, ":recovery_floor", village_pop_min),
        (assign, ":population_cap", village_pop_max),
      (else_try),
        (is_between, ":center_no", towns_begin, towns_end),
        (assign, ":recovery_floor", town_pop_min),
        (assign, ":population_cap", town_pop_max),
      (else_try),
        (is_between, ":center_no", castles_begin, castles_end),
        (assign, ":recovery_floor", village_pop_min),
        (assign, ":population_cap", town_pop_max),
      (try_end),
      (gt, ":recovery_floor", 0),
      (val_add, ":population_cap", 1),

      (assign, ":population_was_invalid", 0),
      (try_begin),
        (lt, ":population", ":recovery_floor"),
        (assign, ":population", ":recovery_floor"),
        (assign, ":population_was_invalid", 1),
      (else_try),
        (gt, ":population", ":population_cap"),
        (assign, ":population", ":population_cap"),
        (assign, ":population_was_invalid", 1),
      (try_end),
      (party_set_slot, ":center_no", slot_center_sod_local_population, ":population"),

      (party_get_slot, ":wealth", ":center_no", slot_town_wealth),
      (val_clamp, ":wealth", 0, 2000001),
      (party_set_slot, ":center_no", slot_town_wealth, ":wealth"),

      (party_get_slot, ":local_prosperity", ":center_no", slot_center_sod_local_prosperity),
      (val_clamp, ":local_prosperity", 0, 101),
      (party_set_slot, ":center_no", slot_center_sod_local_prosperity, ":local_prosperity"),

      (party_get_slot, ":health", ":center_no", slot_center_sod_local_health),
      (val_clamp, ":health", -100, 121),
      (party_set_slot, ":center_no", slot_center_sod_local_health, ":health"),

      (party_get_slot, ":prosperity", ":center_no", slot_town_prosperity),
      (val_clamp, ":prosperity", 0, 121),
      (party_set_slot, ":center_no", slot_town_prosperity, ":prosperity"),

      (party_get_slot, ":food_store", ":center_no", slot_party_food_store),
      (call_script, "script_center_get_food_store_limit", ":center_no"),
      (assign, ":food_limit", reg0),
      (val_max, ":food_limit", 1),
      (val_clamp, ":food_store", 0, ":food_limit"),
      (party_set_slot, ":center_no", slot_party_food_store, ":food_store"),

      (party_get_slot, ":accumulated_rents", ":center_no", slot_center_accumulated_rents),
      (val_clamp, ":accumulated_rents", 0, 2000001),
      (party_set_slot, ":center_no", slot_center_accumulated_rents, ":accumulated_rents"),

      (try_begin),
        (eq, ":population_was_invalid", 1),
        (neg|is_between, ":center_no", castles_begin, castles_end),
        (call_script, "script_change_center_prosperity", ":center_no", -10),
      (try_end),
      (try_begin),
        (eq, ":population_was_invalid", 1),
      (call_script, "script_change_center_health", ":center_no", -15),
      (try_end),
      (try_begin),
        (is_between, ":center_no", villages_begin, villages_end),
        (party_get_slot, ":cattle", ":center_no", slot_village_number_of_cattle),
        (val_clamp, ":cattle", 0, 201),
        (try_begin),
          (eq, ":population_was_invalid", 1),
          (val_min, ":cattle", 2),
        (try_end),
        (party_set_slot, ":center_no", slot_village_number_of_cattle, ":cattle"),
      (try_end),
      (assign, reg0, ":population_was_invalid"),
    (try_end),
  ]),
("sod_normalize_all_center_populations",
  [
    (try_for_range, ":center_no", centers_begin, centers_end),
      (call_script, "script_sod_normalize_center_population", ":center_no"),
    (try_end),
  ]),
]
