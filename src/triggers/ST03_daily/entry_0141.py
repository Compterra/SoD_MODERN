SIMPLE_TRIGGERS = [
(24,
  [
    (neq, "$sod_royal_cur_mission", 0),
    (store_current_day, ":cur_day"),
    (ge, ":cur_day", "$sod_royal_mission_end"),

    (try_begin),
      (eq, "$sod_royal_mission_success", -1),
      (call_script, "script_sod_royal_set_mission_state", "$sod_royal_cur_mission", 0),
      (jump_to_menu, "mnu_sod_royal_diseaster"),
    (else_try),
      (eq, "$sod_royal_mission_success", 0),
      (call_script, "script_sod_royal_set_mission_state", "$sod_royal_cur_mission", 0),
      (jump_to_menu, "mnu_sod_royal_failure"),
    (else_try),
      (eq, "$sod_royal_mission_success", 1),
      (call_script, "script_sod_royal_set_mission_state", "$sod_royal_cur_mission", 0),
      (jump_to_menu, "mnu_sod_royal_success"),
    (else_try),
      (eq, "$sod_royal_mission_success", 2),
      (call_script, "script_sod_royal_set_mission_state", "$sod_royal_cur_mission", 2),
      (jump_to_menu, "mnu_sod_royal_location"),
    (else_try),
      (eq, "$sod_royal_mission_success", 3),
      (call_script, "script_sod_royal_set_mission_state", "$sod_royal_cur_mission", 0),
      (jump_to_menu, "mnu_sod_royal_empty"),
    (try_end),
  ]),
]
