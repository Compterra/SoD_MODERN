MENUS = [
("game_options_2", mnf_enable_hot_keys,
    "{s1}",
    "none",
    [
      (set_background_mesh, "mesh_pic_report_screen"),
      (str_clear, s1),
      (str_store_string, s1, "@Battles settings :"),

      (try_begin),
        (eq, "$g_disable_formations", 0),
        (str_store_string, s1, "@{s1}^^Tactical Formations: ON (AIs will use formations as well)"),
      (else_try),
        (str_store_string, s1, "@{s1}^^Tactical Formations: OFF (AIs won't use formations as well)"),
      (try_end),

	  (try_begin),
        (eq, "$g_disable_formations_dismount", 0),
        (str_store_string, s1, "@{s1}^Auto Dismount: ON (if mounted units are few they start battles dismounted)"),
      (else_try),
        (str_store_string, s1, "@{s1}^Auto Dismount: OFF"),
      (try_end),

	  (try_begin),
        (eq, "$g_disable_morale", 0),
        (str_store_string, s1, "@{s1}^Routing when Morale is low: ON"),
      (else_try),
        (str_store_string, s1, "@{s1}^Routing when Morale is low: OFF"),
      (try_end),

       (try_begin),
         (eq, "$g_sod_deactivate_forced_rest", 1),
         (str_store_string, s1, "@{s1}^Forced Rest After Battles: OFF"),
         (else_try),
         (eq, "$g_sod_deactivate_forced_rest", 0),
         (str_store_string, s1, "@{s1}^Forced Rest After Battles: ON (after a win you may have to wait for a duration based upon morale and battle size)"),
       (try_end),

         (try_begin),
         (eq, "$g_sod_autoresolve", 1),
         (str_store_string, s1, "@{s1}^Autoresolved Battles: Kt0's Improved Autoresolve (recommended realistic mode; troop equipment, roles, and siege context matter)"),
         (else_try),
         (eq, "$g_sod_autoresolve", 0),
         (str_store_string, s1, "@{s1}^Autoresolved Battles: Blood Bath System (fast AIvsAI battles, troop types matter)"),
         (else_try),
         (str_store_string, s1, "@{s1}^Autoresolved Battles: Native System (slow AI vs AI battles, only based on level)"),
         (try_end),
      # Sod Twan
    ],
    [ ("game_options_enable_formations", [(eq, "$g_disable_formations", 1)], "Enable tactical formations", [(assign, "$g_disable_formations", 0), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_disable_formations", [(eq, "$g_disable_formations", 0)], "Disable tactical formations", [(assign, "$g_disable_formations", 1), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_enable_dismount", [(eq, "$g_disable_formations", 0), (eq, "$g_disable_formations_dismount", 1)], "Enable Auto Dismount", [(assign, "$g_disable_formations_dismount", 0), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_disable_dismount", [(eq, "$g_disable_formations", 0), (eq, "$g_disable_formations_dismount", 0)], "Disable Auto Dismount", [(assign, "$g_disable_formations_dismount", 1), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_enable_morale", [(eq, "$g_disable_morale", 1)], "Enable Routing when morale is low", [(assign, "$g_disable_morale", 0), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_disable_morale", [(eq, "$g_disable_morale", 0)], "Disable Routing when morale is low", [(assign, "$g_disable_morale", 1), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_enable_rest", [(eq, "$g_sod_deactivate_forced_rest", 1)], "Forced Rest after Battles", [(assign, "$g_sod_deactivate_forced_rest", 0), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_disable_rest", [(eq, "$g_sod_deactivate_forced_rest", 0)], "No Forced Rest after Battles", [(assign, "$g_sod_deactivate_forced_rest", 1), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_autoresolve_1", [(eq, "$g_sod_autoresolve", 1)], "Use Native Autoresolved Battles", [(assign, "$g_sod_autoresolve", -1), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_autoresolve_2", [(eq, "$g_sod_autoresolve", 0)], "Use KT0 System for Autoresolved Battles", [(assign, "$g_sod_autoresolve", 1), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_autoresilve_3", [(eq, "$g_sod_autoresolve", -1)], "Use Bloodbath for Autoresolved Battles", [(assign, "$g_sod_autoresolve", 0), (jump_to_menu, "mnu_game_options_2")]),
      ("game_options_return", [], "Back to Options...", [(jump_to_menu, "mnu_game_options")]),
    ] ),
]
